# ---------- Step 4：知识图谱（Mermaid · 横版） ----------
def graph_system(pre_prompt: str) -> str:
    return (
        "你是逻辑结构可视化专家。基于课堂纪要，把老师的观点与论证关系画成一张【横版】 Mermaid 流程图。\n\n"
        "【硬性要求】\n"
        "1) 第一行必须是 `flowchart LR`（**横版从左到右**，绝对不要用 TD/TB）。\n"
        "2) 节点数量原则上 18-35 个，深度控制在 4 层以内（**核心观点 → 子论点 → 论据 → 例证**）；"
        "内容特别丰富的课堂可适当增加，但【宁可合并近似论据，也不要碎片化】、不要让单条分支过长。\n"
        "3) 节点文字简洁（每个节点不超过 14 个汉字 / 30 字符），长文本拆成多节点。\n"
        "4) 在【连线上标注关系类型】，例如：A -->|支撑| B、A -->|因果| B、A -->|对比| B、A -->|递进| B、A -->|实证| B。\n"
        "5) 不同核心观点用不同分支，可以用 subgraph 把每个核心观点的子树包起来，subgraph 标题作为该分支的主题；"
        "各分支【按授课先后从左到右排列】（先讲的在左，后讲的在右）。\n"
        "6) 【全图必须连通，不允许任何孤立节点或孤立分支】：\n"
        "   - 必须有一个【总根节点】代表课程主题（放在最左）；\n"
        "   - 根节点必须与【每一个 subgraph 的首要节点】连线，并标注关系（如 -->|展开| 、 -->|包含|）；\n"
        "   - 分支之间至少再加 max(2, 分支数-1) 条【跨分支关系线】（递进/因果/对比），"
        "体现课程论证主线由前到后的推进顺序；\n"
        "   - 每个节点都必须至少有一条连线，绝不能有游离在外、没有任何箭头相连的节点或整段分支。\n"
        "7) 节点文本若含括号、引号、英文等特殊字符，**必须用双引号包裹**，例如 A[\"WACC：加权平均资本成本\"]。\n"
        "8) **不要**在代码里写任何 style/classDef/linkStyle 指令——颜色与字体由前端统一应用主题。\n\n"
        "只输出 Mermaid 代码本身，用 ```mermaid 代码块包裹，不要任何额外解释。"
        + _bg(pre_prompt)
    )


def graph_user(minutes_md: str, chapters_outline: Optional[str] = None) -> str:
    chapters_outline = (chapters_outline or "").strip()
    tail = ""
    if chapters_outline:
        tail = (
            "\n\n【课堂纲目标题（授课顺序参考——分支请据此从左到右排列）】\n"
            f"{chapters_outline}"
        )
    return f"课堂纪要：\n\n{minutes_md}{tail}"


# ---------------- 通用：持续迭代修订 ----------------
def revise_system(product_title: str, pre_prompt: str, is_graph: bool = False, persona: str = "") -> str:
    """对某个已生成产出按用户修订意见再生成。保持原产出的格式与结构。"""
    fmt = (
        "本产出是一张 Mermaid 流程图（横版 `flowchart LR`）。修订后仍只输出 Mermaid 代码，"
        "用 ```mermaid 代码块包裹，第一行保持 `flowchart LR`，不要写 style/classDef/linkStyle，"
        "节点含特殊字符用双引号包裹。"
        if is_graph
        else "本产出是 Markdown 文档。修订后输出【完整的】Markdown 正文，保持原有的章节结构与排版风格。"
    )
    return (
        f"你正在迭代修订一份已生成的课堂产出：「{product_title}」。\n"
        "下面会给你【当前版本内容】和【用户的修订意见】。请严格按修订意见调整，"
        "只改动意见涉及之处，其余内容保持不变；不要遗漏、不要无故重写未提及的部分。\n\n"
        f"{fmt}\n\n"
        "安全红线：不得改动数字、金额、日期、百分比、人名、公司名、机构名；拿不准时保留原文。\n"
        "只输出修订后的产出本身，不要加任何说明、前后缀或对改动的描述。"
        + _persona(persona)
        + _bg(pre_prompt)
    )


def revise_user(current_content: str, instruction: str) -> str:
    return (
        f"【当前版本内容】\n{current_content}\n\n"
        f"【用户的修订意见】\n{instruction.strip()}"
    )
